export function scanPinError(message: string | undefined, t: ScanPinCopy) {
  if (message?.includes('wrong_challenge')) return t.wrong;
  if (message?.includes('alias_taken')) return t.nameTaken;
  if (message?.includes('window_expired')) return t.expired;
  if (message?.includes('student_cap')) return t.cap;
  if (message?.includes('window_full')) return t.full;
  if (message?.includes('coded_class')) return t.coded;
  return t.error;
}
